const LanguageProvider = ({ children }) => {
  const [language, setLanguageState] = useState(() => {
    const saved = localStorage.getItem('podbbang_language');
    if (saved === 'en' || saved === 'ko') return saved;
    return navigator.language?.toLowerCase().startsWith('ko') ? 'ko' : 'en';
  });

  useEffect(() => {
    document.documentElement.lang = language;
    document.title = language === 'ko' ? '팟빵 비공식 앱' : 'Podbbang Unofficial';
    localStorage.setItem('podbbang_language', language);
  }, [language]);

  const setLanguage = useCallback(next => {
    if (next === 'en' || next === 'ko') setLanguageState(next);
  }, []);

  const t = useCallback((text, values = {}) => {
    let translated = language === 'ko' ? korean[text] || text : text;
    if (language === 'ko' && translated === text) {
      const httpError = /^Podbbang request failed \(HTTP (\d+)\)\. Try again\.$/.exec(text);
      if (httpError) translated = korean['Podbbang request failed (HTTP {status}). Try again.'];
    }
    if (language === 'ko' && translated !== text && /\{status\}/.test(translated) && !values.status) {
      const httpError = /HTTP (\d+)/.exec(text);
      if (httpError) values = { ...values, status: httpError[1] };
    }
    return translated.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
  }, [language]);

  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

const useTranslation = () => {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useTranslation must be used inside LanguageProvider.');
  return context;
};

export { LanguageProvider, useTranslation };
